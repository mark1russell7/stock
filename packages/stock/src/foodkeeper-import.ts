// The conversion of the FoodKeeper file of USDA FSIS (foodkeeper.json) to the data module src/foodkeeper-data.ts.
// The module is pure: the command scripts/foodkeeper-import.ts of the repository reads the file and writes the output.
// No entry of the package exports this module.

import type { FoodKeeperProduct, FoodKeeperTimed } from "./foodkeeper.ts";

/** The result of an import: the version of the source, the kept products and the count of each skipped pantry time. */
export interface FoodKeeperImport {
  readonly version: { readonly number: number; readonly date: string };
  readonly products: readonly FoodKeeperProduct[];
  readonly skipped: Readonly<Record<string, number>>;
}

type Row = Readonly<Record<string, unknown>>;

const UNITS: Readonly<Record<string, FoodKeeperTimed["unit"]>> = { Days: "day", Weeks: "week", Months: "month", Years: "year", Year: "year" };

function sheet(file: unknown, name: string): Row[] {
  const sheets = (file as { sheets?: unknown } | null)?.sheets;
  const found = Array.isArray(sheets) ? sheets.find((s: { name?: unknown }) => s?.name === name) : undefined;
  if (!found || !Array.isArray(found.data)) throw new RangeError(`the FoodKeeper file has no sheet ${name}`);
  // Each row of the file is a list of cells, and each cell is an object with one key.
  return found.data.map((cells: unknown) => Object.assign({}, ...(Array.isArray(cells) ? cells : [])) as Row);
}

function text(value: unknown): string | null {
  return typeof value === "string" && value.trim() !== "" ? value.replace(/\s+/g, " ").trim() : null;
}

function int(value: unknown): number | undefined {
  return Number.isInteger(value) ? (value as number) : undefined;
}

/** This function gives the date `MM-DD-YYYY` of the file as `YYYY-MM-DD`. It throws a `RangeError` for a different form. */
function isoOfUsDate(value: unknown): string {
  const m = typeof value === "string" ? /^(\d{2})-(\d{2})-(\d{4})$/.exec(value) : null;
  if (!m) throw new RangeError(`the FoodKeeper file has the date ${String(value)}, not MM-DD-YYYY`);
  return `${m[3]}-${m[1]}-${m[2]}`;
}

/**
 * This function gives the products of a FoodKeeper file that have a pantry time in days, weeks, months or years, or the
 * pantry time `Indefinitely`.
 * The time from the date of purchase (`DOP_Pantry_*`) comes first, then the time of storage (`Pantry_*`).
 * The output is sorted by id. A file with a different structure gives a `RangeError`.
 */
export function foodKeeperImport(file: unknown): FoodKeeperImport {
  const versions = sheet(file, "Version").filter((v) => int(v["Data_Version_Number"]) !== undefined);
  if (versions.length === 0) throw new RangeError("the FoodKeeper file has no version");
  const last = versions.reduce((a, b) => ((int(b["Data_Version_Number"]) ?? 0) > (int(a["Data_Version_Number"]) ?? 0) ? b : a));
  const version = { number: int(last["Data_Version_Number"]) ?? 0, date: isoOfUsDate(last["Modified_Date"]) };

  const categories = new Map<unknown, string>();
  for (const c of sheet(file, "Category")) {
    const name = text(c["Category_Name"]);
    const sub = text(c["Subcategory_Name"]);
    if (name !== null) categories.set(c["ID"], sub === null ? name : `${name} / ${sub}`);
  }

  const skipped: Record<string, number> = {};
  const products: FoodKeeperProduct[] = [];
  for (const p of sheet(file, "Product")) {
    const id = int(p["ID"]);
    const name = text(p["Name"]);
    const times = [
      { basis: "purchase", min: p["DOP_Pantry_Min"], max: p["DOP_Pantry_Max"], metric: p["DOP_Pantry_Metric"] },
      { basis: "stored", min: p["Pantry_Min"], max: p["Pantry_Max"], metric: p["Pantry_Metric"] },
    ] as const;
    const time = times.find((t) => t.metric != null || t.max != null);
    if (id === undefined || name === null || !time) continue;
    const base = { id, name, subtitle: text(p["Name_subtitle"]), category: categories.get(p["Category_ID"]) ?? null, keywords: text(p["Keywords"]), basis: time.basis };
    if (time.metric === "Indefinitely") {
      products.push({ ...base, unit: "indefinitely" });
      continue;
    }
    const unit = typeof time.metric === "string" ? UNITS[time.metric] : undefined;
    const max = int(time.max);
    if (unit === undefined || max === undefined || max <= 0) {
      const key = typeof time.metric === "string" ? time.metric : "no unit";
      skipped[key] = (skipped[key] ?? 0) + 1;
      continue;
    }
    const min = int(time.min);
    products.push({
      ...base,
      min: min !== undefined && min > 0 && min <= max ? min : max,
      max,
      unit,
    });
  }
  products.sort((a, b) => a.id - b.id);
  return { version, products, skipped };
}

/** This function gives the text of `src/foodkeeper-data.ts` for an import, with the SHA-256 of the source file. */
export function foodKeeperModule(result: FoodKeeperImport, sha256: string): string {
  return `// This file is generated by scripts/foodkeeper-import.ts. Do not edit it.
// The source: the FoodKeeper data of USDA FSIS, version ${result.version.number} of ${result.version.date}, license CC0 1.0.
// The SHA-256 of the source file: ${sha256}.
// The import keeps ${result.products.length} products. It skips the products with no pantry time, and these pantry times: ${JSON.stringify(result.skipped)}.

import type { FoodKeeperProduct } from "./foodkeeper.ts";

export const FOODKEEPER_VERSION = { number: ${result.version.number}, date: "${result.version.date}" } as const;

export const FOODKEEPER_PRODUCTS: readonly FoodKeeperProduct[] = ${JSON.stringify(result.products, null, 1)};
`;
}
