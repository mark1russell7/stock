// This script makes src/foodkeeper-data.ts from the FoodKeeper file of USDA FSIS (foodkeeper.json, CC0 1.0).
// Start it with the path of the file: node scripts/foodkeeper-import.mjs <path of foodkeeper.json>
// It keeps the pantry times of each product with a time in days, weeks, months or years. The output has a stable order.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const path = process.argv[2];
if (!path) throw new Error("give the path of foodkeeper.json");
const bytes = readFileSync(path);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const file = JSON.parse(bytes.toString("utf8"));
const sheet = (name) => {
  const found = file.sheets?.find((s) => s.name === name);
  if (!found) throw new Error(`the file has no sheet ${name}`);
  return found.data.map((cells) => Object.assign({}, ...cells));
};

const versions = sheet("Version");
const last = versions.reduce((a, b) => (b.Data_Version_Number > a.Data_Version_Number ? b : a));
const [month, day, year] = String(last.Modified_Date).split("-");
const categories = new Map(sheet("Category").map((c) => [c.ID, c.Subcategory_Name ? `${c.Category_Name} / ${c.Subcategory_Name}` : c.Category_Name]));

const UNITS = { Days: "day", Weeks: "week", Months: "month", Years: "year", Year: "year" };
const clean = (text) => (typeof text === "string" && text.trim() !== "" ? text.replace(/\s+/g, " ").trim() : null);
const skipped = {};
const products = [];
for (const p of sheet("Product")) {
  // The columns DOP_Pantry_* count from the date of purchase. The columns Pantry_* count from the start of the storage.
  const times = [
    ["purchase", p.DOP_Pantry_Min, p.DOP_Pantry_Max, p.DOP_Pantry_Metric],
    ["stored", p.Pantry_Min, p.Pantry_Max, p.Pantry_Metric],
  ];
  const time = times.find(([, , max, metric]) => metric != null || max != null);
  if (!time) continue;
  const [basis, min, max, metric] = time;
  const unit = UNITS[metric];
  if (!unit || !Number.isInteger(max) || max <= 0) {
    skipped[metric ?? "no unit"] = (skipped[metric ?? "no unit"] ?? 0) + 1;
    continue;
  }
  products.push({
    id: p.ID,
    name: clean(p.Name),
    subtitle: clean(p.Name_subtitle),
    category: categories.get(p.Category_ID) ?? null,
    keywords: clean(p.Keywords),
    basis,
    min: Number.isInteger(min) && min > 0 ? min : max,
    max,
    unit,
  });
}
products.sort((a, b) => a.id - b.id);

const out = `// This file is generated by scripts/foodkeeper-import.mjs. Do not edit it.
// The source: the FoodKeeper data of USDA FSIS, version ${last.Data_Version_Number} of ${year}-${month}-${day}, license CC0 1.0.
// The SHA-256 of the source file: ${sha256}.
// The import keeps ${products.length} products. It skips the products with no pantry time, and these pantry times: ${JSON.stringify(skipped)}.

import type { FoodKeeperProduct } from "./foodkeeper.ts";

export const FOODKEEPER_VERSION = { number: ${last.Data_Version_Number}, date: "${year}-${month}-${day}" } as const;

export const FOODKEEPER_PRODUCTS: readonly FoodKeeperProduct[] = ${JSON.stringify(products, null, 1)};
`;
writeFileSync(new URL("../src/foodkeeper-data.ts", import.meta.url), out);
console.log(`products ${products.length}, version ${last.Data_Version_Number} ${year}-${month}-${day}, skipped ${JSON.stringify(skipped)}`);
